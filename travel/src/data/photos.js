/** Photo metadata resolved for one language. */
function photo(slug, lang) {
  const p = P[slug];
  if (!p) throw new Error('Unknown photo: ' + slug);
  const t = p[lang] || p.en;
  return { slug, cat: p.cat, pos: p.pos, location: t[0], title: t[1], desc: t[2], story: t[3] };
}

const bySlug = (cat) => Object.keys(P).filter((s) => P[s].cat === cat);

module.exports = { P, CATEGORIES, photo, bySlug, all: Object.keys(P) };
